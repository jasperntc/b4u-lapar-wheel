// Compares the raw OSM and Overture pulls and writes the report and the
// candidates CSV. Run with `npm run data:compare`. Reads only data/raw/.
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { buildCandidates, osmId, osmName, osmPoint, overtureType, toCsv, type OsmElement, type OvertureRow } from "./candidates.ts";
import { cuisineFromOsm, cuisineFromOverture } from "./cuisine.ts";
import { MAX_METERS, MIN_SIMILARITY } from "./match.ts";
import { seededSample } from "./sample.ts";

const BOX = { south: 5.865, west: 116.035, north: 6.05, east: 116.175 };
const SEED = 1;
const RAW = "data/raw";

function latest(pattern: RegExp): string {
  const file = readdirSync(RAW).filter((f) => pattern.test(f)).sort().at(-1);
  if (!file) throw new Error(`No file matching ${pattern} in ${RAW}. Run npm run data:pull first.`);
  return `${RAW}/${file}`;
}
const readJson = (path: string) => JSON.parse(readFileSync(path, "utf8"));

const osmFile = latest(/^osm-kk-\d{4}-\d{2}-\d{2}\.json$/);
const areasFile = latest(/^osm-kk-areas-\d{4}-\d{2}-\d{2}\.json$/);
const overtureFile = latest(/^overture-kk-.+\.json$/);

const osmRaw = readJson(osmFile);
const osm: OsmElement[] = osmRaw.elements;
const areas = (readJson(areasFile).elements as OsmElement[])
  .filter((e) => e.tags?.name)
  .map((e) => ({ name: e.tags!.name, ...osmPoint(e) }));
// Named places need coordinates, or every nearest-area lookup quietly returns "".
if (!areas.length || areas.some((p) => !Number.isFinite(p.lat) || !Number.isFinite(p.lon))) {
  throw new Error(`${areasFile} has places without coordinates. Its query must end in "out;", not "out tags;".`);
}
const overtureRaw = readJson(overtureFile);
const overture: OvertureRow[] = overtureRaw.rows;

const { candidates, matches } = buildCandidates(osm, overture, areas);

// Self-checks: every row inside the box, and nothing lost or double-counted.
for (const c of candidates) {
  const [lat, lon] = [Number(c.lat), Number(c.lon)];
  if (!(lat >= BOX.south && lat <= BOX.north && lon >= BOX.west && lon <= BOX.east)) {
    throw new Error(`${c.candidate_id} is outside the box: ${c.lat}, ${c.lon}`);
  }
}
if (candidates.length !== osm.length + overture.length - matches.length) throw new Error("Candidate count doesn't add up");

writeFileSync("data/candidates-kk.csv", toCsv(candidates));

// ---- Report ----
const cell = (v: unknown) => String(v ?? "").replaceAll("|", "\\|").replaceAll("\n", " ");
const table = (head: string[], rows: unknown[][]) =>
  [`| ${head.join(" | ")} |`, `|${head.map(() => "---").join("|")}|`, ...rows.map((r) => `| ${r.map(cell).join(" | ")} |`)].join("\n");
const pct = (n: number, of: number) => (of ? `${n} (${Math.round((100 * n) / of)}%)` : "0");
const count = <T,>(items: readonly T[], key: (t: T) => string) => {
  const m = new Map<string, number>();
  for (const t of items) m.set(key(t), (m.get(key(t)) ?? 0) + 1);
  return [...m].sort((a, b) => b[1] - a[1]);
};

const TYPES = ["restaurant", "cafe", "fast_food", "food_court"];
const osmType = (e: OsmElement) => e.tags?.amenity ?? "";
const matchedOsm = new Set(matches.map((m) => m.osmId));
const matchedOverture = new Set(matches.map((m) => m.overtureId));
const meters = matches.map((m) => m.meters).sort((a, b) => a - b);
const osmById = new Map(osm.map((e) => [osmId(e), e]));
const overtureById = new Map(overture.map((r) => [r.id, r]));
const hasAddr = (e: OsmElement) => Object.keys(e.tags ?? {}).some((k) => k.startsWith("addr:"));

const deciles = Array.from({ length: 10 }, (_, i) => {
  const lo = i / 10;
  const n = overture.filter((r) => r.confidence != null && r.confidence >= lo && (i === 9 ? r.confidence <= 1 : r.confidence < lo + 0.1)).length;
  return [`${lo.toFixed(1)}–${(lo + 0.1).toFixed(1)}`, n];
});

const licences = count(
  overture.flatMap((r) => [...new Set((r.sources ?? []).map((s) => `${s.dataset ?? "?"}|${s.license ?? "?"}`))]),
  (k) => k,
).map(([k, n]) => [...k.split("|"), n]);

const osmLink = (id: string) => `[${id}](https://www.openstreetmap.org/${id})`;

const report = `# Greater KK: OpenStreetMap and Overture compared

Generated by \`npm run data:compare\`. This is a report only: it makes no keep or drop decisions. Pruning happens by hand in \`data/candidates-kk.csv\`, following [README.md](README.md).

## Sources

${table(["Source", "File", "Data as of", "Places"], [
  ["OpenStreetMap (Overpass)", osmFile, osmRaw.osm3s?.timestamp_osm_base ?? "?", osm.length],
  ["Overture Maps", overtureFile, `release ${overtureRaw.release}, pulled ${overtureRaw.pulledAt}`, overture.length],
  ["OSM named places (for areas)", areasFile, "", areas.length],
])}

Box: south ${BOX.south}, west ${BOX.west}, north ${BOX.north}, east ${BOX.east}.

## Places per type

${table(["Type", "OSM", "Overture"], TYPES.map((t) => [t, osm.filter((e) => osmType(e) === t).length, overture.filter((r) => overtureType(r) === t).length]))}

Overture by \`basic_category\`:

${table(["basic_category", "Places"], count(overture, (r) => r.basic_category))}

## Matches

Rule: an OSM place and an Overture place are the same restaurant when they are within ${MAX_METERS} m of each other **and** their names are at least ${MIN_SIMILARITY} alike. Names are compared after lowercasing and dropping accents, punctuation and generic words such as "restoran", "kedai", "kopi" and "sdn bhd". The score is 1 when one name's words all appear in the other, otherwise the share of words in common. Pairs are one-to-one, taken closest first. Names in different scripts (Chinese characters and Latin) never match.

${table(["", "Places"], [
  ["Matched (in both)", matches.length],
  ["OSM only", osm.length - matches.length],
  ["Overture only", overture.length - matches.length],
  ["Candidate rows", candidates.length],
  ["Median match distance", meters.length ? `${meters[Math.floor(meters.length / 2)].toFixed(0)} m` : "n/a"],
])}

15 random matches (seed ${SEED}):

${table(["OSM", "OSM name", "Overture name", "Distance", "Similarity"], seededSample(matches, 15, SEED).map((m) => [
  osmLink(m.osmId), osmName(osmById.get(m.osmId)!), overtureById.get(m.overtureId)?.name, `${m.meters.toFixed(0)} m`, m.similarity.toFixed(2),
]))}

## Field completeness

${table(["Field", "OSM", "Overture"], [
  ["Name", pct(osm.filter((e) => osmName(e)).length, osm.length), pct(overture.filter((r) => r.name).length, overture.length)],
  ["Cuisine in the source (OSM \`cuisine\`, Overture category below \`restaurant\`)", pct(osm.filter((e) => e.tags?.cuisine).length, osm.length), pct(overture.filter((r) => (r.taxonomy_hierarchy?.length ?? 0) > 2).length, overture.length)],
  ["Cuisine mapped to the short list", pct(osm.filter((e) => cuisineFromOsm(e.tags ?? {})).length, osm.length), pct(overture.filter((r) => cuisineFromOverture(r.taxonomy_hierarchy ?? [], r.name ?? "")).length, overture.length)],
  ["Address or area", pct(osm.filter(hasAddr).length, osm.length), pct(overture.filter((r) => r.addresses?.length).length, overture.length)],
  ["Opening hours", pct(osm.filter((e) => e.tags?.opening_hours).length, osm.length), "n/a (no hours field)"],
  ["In both sources", pct(matchedOsm.size, osm.length), pct(matchedOverture.size, overture.length)],
])}

## Overture confidence and status

No confidence filter was applied. Spread:

${table(["Confidence", "Places"], [...deciles, ["missing", overture.filter((r) => r.confidence == null).length]])}

${table(["operating_status", "Places"], count(overture, (r) => r.operating_status ?? "missing"))}

## Overture licences

Each Overture place lists the datasets it came from. Places per dataset and licence:

${table(["Dataset", "Licence", "Places"], licences)}

## Spot check: 20 random OSM places (seed ${SEED})

${table(["OSM", "Name", "Amenity", "cuisine tag", "Proposed cuisine", "Area tags"], seededSample(osm, 20, SEED).map((e) => [
  osmLink(osmId(e)), osmName(e), e.tags?.amenity, e.tags?.cuisine, cuisineFromOsm(e.tags ?? {}),
  Object.entries(e.tags ?? {}).filter(([k]) => /^addr:(suburb|city|street)$/.test(k)).map(([k, v]) => `${k}=${v}`).join("; "),
]))}

## Spot check: 20 random Overture places (seed ${SEED})

${table(["Overture id", "Name", "basic_category", "taxonomy.primary", "Proposed cuisine", "Confidence", "Status", "Locality"], seededSample(overture, 20, SEED).map((r) => [
  r.id, r.name, r.basic_category, r.taxonomy_primary, cuisineFromOverture(r.taxonomy_hierarchy ?? [], r.name ?? ""),
  r.confidence?.toFixed(2), r.operating_status, r.addresses?.[0]?.locality,
]))}
`;

writeFileSync("docs/data/kk-comparison.md", report);
console.log(`${candidates.length} candidates (${matches.length} matched) → data/candidates-kk.csv, docs/data/kk-comparison.md`);
